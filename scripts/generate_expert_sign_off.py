"""Generates docs/pilot/expert-sign-off-sheet.md from the jurisdiction pack.

Scans /jurisdiction/ma/*.yaml for every key with status: needs_expert, extracting:
- key
- file
- value
- regulatory question / TODO(EXPERT)

Usage:
    python scripts/generate_expert_sign_off.py          # Regenerates docs/pilot/expert-sign-off-sheet.md
    python scripts/generate_expert_sign_off.py --check  # Verifies up-to-date status (CI gate)
"""

from __future__ import annotations

import argparse
import pathlib
import sys
from typing import Any

import yaml

REPO_ROOT = pathlib.Path(__file__).resolve().parent.parent
PACK_DIR = REPO_ROOT / "jurisdiction" / "ma"
OUTPUT_FILE = REPO_ROOT / "docs" / "pilot" / "expert-sign-off-sheet.md"


def format_value(val: Any) -> str:
    if val is None:
        return "*Non défini (null)*"
    if isinstance(val, (str, int, float, bool)):
        return f"`{val}`"
    if isinstance(val, dict):
        items = [f"{k}: {v}" for k, v in list(val.items())[:3]]
        preview = ", ".join(items)
        if len(val) > 3:
            preview += f" ... (+{len(val)-3})"
        return f"`{{{preview}}}`"
    if isinstance(val, list):
        items = [str(x) for x in val[:3]]
        preview = ", ".join(items)
        if len(val) > 3:
            preview += f" ... (+{len(val)-3})"
        return f"`[{preview}]`"
    return f"`{str(val)[:40]}`"


def extract_needs_expert_entries() -> list[dict[str, Any]]:
    entries: list[dict[str, Any]] = []

    for yaml_path in sorted(PACK_DIR.glob("*.yaml")):
        rel_path = f"jurisdiction/ma/{yaml_path.name}"
        try:
            content = yaml.safe_load(yaml_path.read_text(encoding="utf-8"))
        except (yaml.YAMLError, OSError) as ex:
            print(f"Error reading {yaml_path}: {ex}", file=sys.stderr)
            continue

        if not isinstance(content, list):
            continue

        for item in content:
            if not isinstance(item, dict):
                continue

            if item.get("status") == "needs_expert":
                key = item.get("key", "unnamed_key")
                val = item.get("value")
                note = item.get("note") or item.get("source") or "TODO(EXPERT): Validation requise"
                entries.append({
                    "file": rel_path,
                    "key": key,
                    "value": format_value(val),
                    "question": note.strip(),
                })

    return entries


def generate_markdown(entries: list[dict[str, Any]]) -> str:
    lines: list[str] = [
        "# AVENEL — Fiche de Visa et d'Arbitrage des Règles Réglementaires (`needs_expert`)",
        "",
        "<!-- GENERATED BY scripts/generate_expert_sign_off.py — DO NOT EDIT MANUALLY -->",
        "",
        "**Cabinet partenaire :** Cabinet d'Expertise Comptable Pilote  ",
        "**Expert-comptable responsable :** ............................................................  ",
        "**N° d'inscription à l'Ordre (OEC) :** ......................................................  ",
        "**Date d'arbitrage :** ...... / ...... / 2026  ",
        "**Référence :** Règle Obligatoire Part A.1 (« Ne jamais inventer une règle de droit ») & Invariant K.2.",
        "",
        f"**Nombre de règles nécessitant confirmation par un professionnel :** {len(entries)} règles extraites du pack.",
        "",
        "---",
        "",
        "## 1. Inventaire Exhaustif des Clés Réglementaires en Statut `needs_expert`",
        "",
        "Pour chaque point ci-dessous, la plateforme applique un comportement de précaution (avertissement ou absence d'affectation automatique). L'expert est invité à viser l'interprétation retenue pour le cabinet.",
        "",
        "| Réf | Fichier Source | Clé Réglementaire | Valeur Actuelle | Question / Arbitrage Requis (`TODO(EXPERT)`) | Arbitrage Cabinet | Visa Expert |",
        "| :---: | :--- | :--- | :--- | :--- | :--- | :---: |",
    ]

    for idx, e in enumerate(entries, 1):
        ref = f"EXP-{idx:02d}"
        file_md = f"`{e['file']}`"
        key_md = f"`{e['key']}`"
        # Sanitize pipes in value or question
        val_clean = e["value"].replace("|", "\\|")
        q_clean = e["question"].replace("|", "\\|").replace("\n", " ")
        lines.append(
            f"| **{ref}** | {file_md} | {key_md} | {val_clean} | {q_clean} | [ ] Approuvé<br>[ ] Corrigé | ________ |"
        )

    lines.extend([
        "",
        "---",
        "",
        "## 2. Déclaration Formelle de l'Expert-Comptable Signataire",
        "",
        "Je soussigné(e), ...................................................................................., agissant en qualité d'expert-comptable inscrit au tableau de l'Ordre des Experts-Comptables du Maroc sous le numéro ................................... :",
        "",
        "1. Confirme avoir pris connaissance de l'ensemble des règles de comptabilisation et de détermination fiscale automatisées par la plateforme AVENEL.",
        "2. Déclare validés les arbitrages cochés ci-dessus pour le paramétrage du cabinet et de ses dossiers clients pilotes.",
        "3. Autorise le passage en statut vérifié (`status: verified`) des clés visées dès intégration dans les fichiers de juridiction correspondants.",
        "",
        "**Fait à :** .......................................................  ",
        "**Le :** ...... / ...... / 2026  ",
        "",
        "**Signature et cachet professionnel :**  ",
        "<br><br><br>",
        "_____________________________________________________",
        "",
    ])

    return "\n".join(lines)


def main() -> int:
    parser = argparse.ArgumentParser(description="Generate expert sign-off sheet from jurisdiction pack.")
    parser.add_argument("--check", action="store_true", help="Check if the committed document matches generated output.")
    args = parser.parse_args()

    entries = extract_needs_expert_entries()
    generated_md = generate_markdown(entries)

    if args.check:
        if not OUTPUT_FILE.exists():
            print(f"FAIL: {OUTPUT_FILE} does not exist. Run python scripts/generate_expert_sign_off.py", file=sys.stderr)
            return 1

        existing_md = OUTPUT_FILE.read_text(encoding="utf-8").replace("\r\n", "\n")
        normalized_gen = generated_md.replace("\r\n", "\n")

        if existing_md != normalized_gen:
            print(
                f"FAIL: {OUTPUT_FILE} is out of date with jurisdiction pack. "
                f"Run 'python scripts/generate_expert_sign_off.py' to update.",
                file=sys.stderr,
            )
            return 1

        print(f"PASS: {OUTPUT_FILE} is up to date with {len(entries)} needs_expert rules.")
        return 0

    OUTPUT_FILE.write_text(generated_md, encoding="utf-8")
    print(f"Generated {OUTPUT_FILE} with {len(entries)} needs_expert rules.")
    return 0


if __name__ == "__main__":
    sys.exit(main())
